// Generates docs/rules.md from the rule metadata so the docs cannot drift from the code.
import { writeFileSync } from 'node:fs';
import { RULES, VERIFY_RULE } from '../src/rules/index.js';

/** Hand-written examples shown in the docs: [flagged, fine]. */
const EXAMPLES = /** @type {Record<string, [string, string]>} */ ({
  GP001: ['`git rm tests/test_cart.py` while `cart.py` stays', 'deleting `cart.py` and its test together'],
  GP002: ['`+ @pytest.mark.skip`, `+ it.only(`, `+ t.Skip()`, `- assert x` → `+ # assert x`', 'a skip that was already there'],
  GP003: ['`- expect(total).toBe(42)` with no replacement', 'the same assertion moved to another file'],
  GP004: ['`- expect(x).toBe(42)` → `+ expect(x).toBeTruthy()`', '`toBe(42)` → `toBe(43)` (that is GP005)'],
  GP005: ['`- assertEqual(f(2), 4)` → `+ assertEqual(f(2), 5)`', 'adding a new assertion'],
  GP006: ['a `def test_x` removed from a file that still exists', 'renaming a test'],
  GP007: ['`+ except Exception: pass` in a test, `+ .catch(() => {})`', 'try/except around cleanup in non-test code'],
  GP008: ['`__snapshots__/a.snap` changed lines', 'a brand-new snapshot file'],
  GP009: ['`+ jest.retryTimes(3)`, `+ @pytest.mark.flaky`', 'retries that were already configured'],
  GP010: ['`+ assert True`, `+ expect(true).toBe(true)`', 'real assertions'],
  GP020: ['`+ // @ts-ignore`, `+ # type: ignore`, `+ // eslint-disable-next-line`', 'one pre-existing suppression left untouched'],
  GP030: ['`+ continue-on-error: true`, `+ npm test || true`, `- run: npm run lint`', 'a step that is reworded but still runs the same command'],
  GP031: ['`fail_under = 90` → `70`, `"strict": true` → `false`, a lint rule set to `"off"`', 'raising a threshold'],
  GP032: ['`"test": "jest"` → `"test": "echo ok"`, `+ --deselect tests/x.py`', 'adding flags to the test script that do not exclude tests'],
  GP040: ['`+ if (x === 1234.56) return 246.91;` where a test asserts `1234.56`', 'a new constant no test mentions'],
  GP041: ['`+ if os.environ.get("PYTEST_CURRENT_TEST"):` in application code', 'the same check inside a test helper'],
});

const lines = [
  '# Rules',
  '',
  '<!-- Generated by `npm run docs` from src/rules. Do not edit by hand. -->',
  '',
  'Every finding is a **review prompt**, not a verdict. Weakening a test is sometimes the right call because the spec changed. goalposts makes sure a human decides.',
  '',
  'Silence one line with a comment `goalposts-ignore: GP002` on or directly above it. Silence a rule everywhere with `"ignore": ["GP002"]` in `.goalposts.json`, or change its level with `"severity": { "GP005": "low" }`.',
  '',
  '| ID | Name | Default | What it catches |',
  '|---|---|---|---|',
  ...[...RULES, VERIFY_RULE].map((r) => `| [${r.id}](#${r.id.toLowerCase()}) | ${r.name} | ${r.severity} | ${r.summary} |`),
  '',
];

for (const r of RULES) {
  const [flagged, fine] = EXAMPLES[r.id] ?? ['', ''];
  lines.push(`## ${r.id}`, '', `**${r.name}** · default severity **${r.severity}**`, '', r.summary, '', `*Why it matters:* ${r.why}`, '');
  if (flagged) lines.push(`- Flagged: ${flagged}`, `- Not flagged: ${fine}`, '');
}

lines.push(
  `## ${VERIFY_RULE.id}`,
  '',
  `**${VERIFY_RULE.name}** · only produced with \`--verify "<command>"\``,
  '',
  VERIFY_RULE.summary,
  '',
  `*Why it matters:* ${VERIFY_RULE.why}`,
  '',
  'goalposts copies your project into two temporary directories, runs your command in the first as-is, then restores the pre-change version of every modified or deleted test file in the second and runs it again. If the first passes and the second fails, the change only looks green because the tests moved. Dependency folders (`node_modules`, `.venv`, `venv`, `vendor`) are symlinked, not copied. Your working tree is never modified.',
  '',
  '## What goalposts does not do',
  '',
  '- It does not run an LLM and makes no network calls.',
  '- It cannot judge whether a new expectation is *correct*; it can only show you that it changed.',
  '- Semantic cheating that leaves no textual trace (for example, mocking out the unit under test in a brand-new test) is outside what a diff scan can see.',
  '',
);

writeFileSync(new URL('../docs/rules.md', import.meta.url), lines.join('\n'));
console.log('wrote docs/rules.md');
